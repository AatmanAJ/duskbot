// The brief is a chat message the server writes, so its words come from here in the language set for the person, not from the app's packs.
import { byLanguage } from "../language.ts";

type Count = (count: number) => string;
type Name = (name: string) => string;
type Pair = (first: string, second: string) => string;
type List = (items: string[]) => string;

export interface BriefWords {
  /** Leads the notification's summary. */
  title: string;
  /** Said once, the first time the brief is posted. */
  intro: string;
  nothingNeedsYou: string;
  needsLead: Count;
  /** One list line: what it is, then its note. */
  line: Pair;
  waitingOn: Name;
  today: List;
  meetingAt: Pair;
  alsoLead: string;
  idea: Name;
  noSender: string;
  noSubject: string;
  more: Count;
  waitingMany: string;
  waitingCount: Count;
  summary: { needs: Count; meetings: Count; emails: Count; routines: Count; ideas: Count; nothing: string };
  finished: string;
  failed: Name;
  missed: Name;
  didNotFinish: string;
  signedOut: Name;
  signInAgain: string;
  usageLimit: string;
  reconnecting: Name;
  unreachable: string;
  chooseAnother: string;
  asked: Name;
  aBot: string;
  overlap: Pair;
  both: Pair;
  couldNotRead: Name;
  reconnect: Name;
  tryAgainSoon: string;
  unsorted: string;
  unsortedNote: Name;
  openPage: string;
  unpreparedMeetings: string;
  unpreparedNote: Name;
  isAsking: Name;
}

