/** Every dot of `text` set in the face, one blank column between letters: `lit` is false for an unlit dot of the
 * panel. Letters the face has no glyph for are left out. */
export function signDots(text: string): { columns: number; dots: { x: number; y: number; lit: boolean }[] } {
  const glyphs = [...text.toLowerCase()].map((char) => GLYPHS[char]).filter((rows): rows is readonly string[] => Boolean(rows));
  const dots: { x: number; y: number; lit: boolean }[] = [];
  glyphs.forEach((rows, index) => {
    const left = index * (GLYPH_COLUMNS + 1);
    for (let y = 0; y < GLYPH_ROWS; y++) {
      for (let x = 0; x < GLYPH_COLUMNS + 1; x++) dots.push({ x: left + x, y, lit: x < GLYPH_COLUMNS && rows[y]![x] === "#" });
    }
  });
  return { columns: Math.max(0, glyphs.length * (GLYPH_COLUMNS + 1) - 1), dots: dots.filter((dot) => dot.x < glyphs.length * (GLYPH_COLUMNS + 1) - 1) };
}
